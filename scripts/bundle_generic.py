"""Development-only resource build from an explicitly supplied KiCad installation."""

from pathlib import Path
import argparse
import json
import shutil
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from manager.cad import (
    flatten_symbol,
    symbol_library,
    connector_symbol,
)
from manager.sexpr import parse, children, dump

parser = argparse.ArgumentParser()
parser.add_argument("kicad_share", type=Path)
args = parser.parse_args()
out = Path(__file__).resolve().parents[1] / "resources/generic_models"
for directory in ("symbols", "footprints", "models-3d"):
    (out / directory).mkdir(parents=True, exist_ok=True)
source = (args.kicad_share / "symbols/Device.kicad_sym").read_text()
for kind, original in [("Resistor", "R_US"), ("Capacitor", "C")]:
    (out / f"symbols/{kind}.kicad_sym").write_text(
        symbol_library(flatten_symbol(source, original), kind)
    )
connectors = [
    "kicad_symbol_lib",
    ["version", "20241209"],
    ["generator", "kicad_library_manager"],
]
for count in range(1, 25):
    for layout in ("single", "split"):
        connectors.append(connector_symbol(count, layout))
(out / "symbols/Connectors.kicad_sym").write_text(dump(connectors) + "\n")
packages = {"0402": "1005", "0603": "1608", "0805": "2012", "1206": "3216"}
inventory = []
for family, prefix in [("Resistor", "R"), ("Capacitor", "C")]:
    dest = out / f"footprints/{family}.pretty"
    dest.mkdir(exist_ok=True)
    for imperial, metric in packages.items():
        name = f"{prefix}_{imperial}_{metric}Metric"
        footprint = (
            args.kicad_share / f"footprints/{family}_SMD.pretty/{name}.kicad_mod"
        )
        model = args.kicad_share / f"3dmodels/{family}_SMD.3dshapes/{name}.step"
        shutil.copy2(model, out / f"models-3d/{name}.step")
        # Keep KiCad's supplied transform, replace only its model URI.
        tree = parse(footprint.read_text())
        from manager.sexpr import Quoted

        for n in children(tree, "model"):
            n[1] = Quoted(
                "${MYCO_PARTS_DIR}/../components/generic_models/models-3d/" + name + ".step"
            )
        (dest / f"{name}.kicad_mod").write_text(dump(tree) + "\n")
        inventory.append(
            dict(
                type=family.lower(),
                package=imperial,
                metric=metric,
                symbol=f"symbols/{family}.kicad_sym",
                symbolName=family,
                footprint=f"footprints/{family}.pretty/{name}.kicad_mod",
                model=f"models-3d/{name}.step",
            )
        )
(out / "inventory.json").write_text(json.dumps(inventory, indent=2) + "\n")
(out / "ATTRIBUTION.md").write_text("""# Generic CAD attribution

Resistor and capacitor symbols, footprints, and STEP models are extracted from the KiCad 10.0.1 distribution. Original names are retained in inventory.json where applicable. Source: https://gitlab.com/kicad/libraries . These assets are licensed under CC BY-SA 4.0 with the KiCad libraries exception. See LICENSE-KICAD.md.

The connector layout collection is generated by KiCad Library Manager, using explicitly numbered passive pins. It does not establish manufacturer-specific electrical mappings.
""")
print(
    f"Bundled {len(inventory)} passive package definitions and 48 connector layouts in {out}"
)
